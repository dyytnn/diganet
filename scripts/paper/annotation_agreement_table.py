#!/usr/bin/env python3
"""Generate the manuscript table for the frozen A3 agreement analyses."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

CLASSES = ("ZP", "TE", "ICM", "macro3_complete_cases")


def load_rows(result_dir: Path) -> dict[tuple[str, str], dict]:
    """Load one technically reviewed A3 summary keyed by class and metric."""
    meta = json.loads((result_dir / "meta.json").read_text())
    if meta.get("status") != "PROVISIONAL_TECHNICALLY_REVIEWED":
        raise ValueError(f"Not a technically reviewed A3 result: {result_dir}")
    rows = json.loads((result_dir / "summary.json").read_text())
    selected = {
        (row["class"], row["metric"]): row
        for row in rows
        if row["cohort"] == "technical_visual_review"
    }
    required = {(class_name, metric) for class_name in CLASSES for metric in ("iou", "dice")}
    required |= {
        (class_name, metric) for class_name in CLASSES for metric in ("boundary_f2", "hd95")
    }
    if not required <= set(selected):
        raise ValueError(f"Incomplete A3 result: {result_dir}")
    return selected


def main() -> None:
    """Write a complete LaTeX table from native and 256-grid result JSON."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--native", type=Path, required=True)
    parser.add_argument("--working", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    native = load_rows(args.native)
    working = load_rows(args.working)
    labels = {
        "ZP": "ZP",
        "TE": "TE",
        "ICM": "ICM",
        "macro3_complete_cases": "Macro (ZP/TE/ICM)",
    }
    body = []
    for class_name in CLASSES:
        n_row = working[class_name, "iou"]
        if n_row["n_images"] != 50 or n_row["n_groups"] != 39:
            raise ValueError("Expected 50 images in 39 frozen filename groups")
        ni = native[class_name, "iou"]
        wi = working[class_name, "iou"]
        body.append(
            f"{labels[class_name]} & 50 & "
            f"{ni['mean']:.3f} $\\pm$ {ni['std']:.3f} & "
            f"{wi['mean']:.3f} $\\pm$ {wi['std']:.3f} & "
            f"[{wi['ci95_low']:.3f}, {wi['ci95_high']:.3f}] & "
            f"{working[class_name, 'dice']['mean']:.3f} & "
            f"{working[class_name, 'boundary_f2']['mean']:.3f} & "
            f"{working[class_name, 'hd95']['mean']:.2f} \\\\"
        )
    document = "\n".join(
        [
            "% Generated by scripts/paper/annotation_agreement_table.py; do not edit manually.",
            "\\begin{table*}[t]",
            "\\caption{Pairwise agreement between the released annotation and a second manual reading of the 50-image validation set. Values are means $\\pm$ between-image SD; confidence intervals use 5,000 bootstrap replicates over 39 frozen filename groups. The working-resolution columns use nearest-neighbour resizing to $256\\times256$. Boundary F and HD95 use a 2-pixel tolerance and pixels on that grid, respectively. Background and the derived blastocoel are excluded. The macro row averages ZP, TE and ICM on the same 50 images.}",
            "\\label{tab:annotation-agreement}",
            "\\centering\\footnotesize",
            "\\begin{tabular}{lrrrrrrr}",
            "\\toprule",
            "Class & $n$ & IoU native & IoU $256^2$ & 95\\% CI $256^2$ & Dice $256^2$ & BF@2 & HD95 \\\\",
            "\\midrule",
            *body,
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table*}",
            "",
        ]
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(document)
    print(args.out)


if __name__ == "__main__":
    main()
