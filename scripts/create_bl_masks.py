#!/usr/bin/env python3
"""Copy a blastocyst dataset and derive auditable BL candidate masks.

BL is estimated as the enclosed cavity inside the annotated TE, excluding TE
and ICM. The output is deliberately marked ``derived_candidate``: it is a
bootstrap label for review, not an expert ground truth annotation.
"""
from __future__ import annotations
import argparse, csv, shutil
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage


def binary(path: Path) -> np.ndarray:
    return np.asarray(Image.open(path).convert("L"), dtype=np.uint8) > 0


def save_mask(mask: np.ndarray, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray((mask.astype(np.uint8) * 255), mode="L").save(path)


def derive_bl(te: np.ndarray, icm: np.ndarray, zp: np.ndarray) -> tuple[np.ndarray, str]:
    te_inside = ndimage.binary_fill_holes(te)
    candidate = te_inside & ~te & ~icm
    method = "filled_te_minus_te_icm"
    # A small number of masks are open/fragmented. Use the enclosed ZP region
    # only as a flagged fallback, still excluding all annotated structures.
    if candidate.sum() == 0:
        candidate = ndimage.binary_fill_holes(zp) & ~zp & ~te & ~icm
        method = "filled_zp_fallback_minus_zp_te_icm"
    return candidate, method


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", default="/data/tannd/SSLData/discriminative_data/blastocyst/source")
    parser.add_argument("--output", default="dataset/source")
    parser.add_argument("--no-copy-images", action="store_true")
    args = parser.parse_args()
    source, output = Path(args.source), Path(args.output)
    image_src, mask_src = source / "images", source / "masks"
    image_dst, mask_dst = output / "images", output / "masks"
    image_dst.mkdir(parents=True, exist_ok=True)
    for cls in ("icm", "te", "zp", "bl"):
        (mask_dst / cls).mkdir(parents=True, exist_ok=True)
    if not args.no_copy_images:
        for path in image_src.iterdir():
            if path.is_file(): shutil.copy2(path, image_dst / path.name)
    rows = []
    for image_path in sorted(image_src.iterdir()):
        if not image_path.is_file(): continue
        name = image_path.name
        paths = {c: mask_src / c / name for c in ("icm", "te", "zp")}
        if not all(p.exists() for p in paths.values()):
            rows.append({"image": name, "status": "missing_source_mask"}); continue
        icm, te, zp = (binary(paths[c]) for c in ("icm", "te", "zp"))
        bl, method = derive_bl(te, icm, zp)
        save_mask(bl, mask_dst / "bl" / name)
        if not args.no_copy_images:
            for c in ("icm", "te", "zp"): shutil.copy2(paths[c], mask_dst / c / name)
        rows.append({"image": name, "status": "derived_candidate", "method": method,
                     "icm_pixels": int(icm.sum()), "te_pixels": int(te.sum()),
                     "zp_pixels": int(zp.sum()), "bl_pixels": int(bl.sum()),
                     "bl_fraction": float(bl.mean())})
    with (output / "bl_derivation_qc.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=sorted({k for row in rows for k in row})); writer.writeheader(); writer.writerows(rows)
    (output / "BL_LABEL_PROVENANCE.md").write_text("""# BL label provenance\n\nThese BL masks are `derived_candidate` labels, not expert ground truth. They are generated by filling enclosed TE holes, subtracting TE and ICM, with a ZP fallback for open/fragmented TE masks. Review them manually and do not use them for the final SOTA claim until an embryologist validates them.\n""")
    print(f"wrote {len(rows)} records to {output}; review {output / 'bl_derivation_qc.csv'}")


if __name__ == "__main__": main()
